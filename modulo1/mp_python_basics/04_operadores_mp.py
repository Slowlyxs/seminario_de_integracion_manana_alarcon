#Operadores Matematicos
pasaje = 150.00
iva = 0.15
print("Suma")
print(pasaje,"+",iva ,"=",pasaje+iva)

print("Resta")
print(pasaje,"-",iva ,"=",pasaje-iva)

print("Multiplicacion")
print(pasaje,"*",iva ,"=",pasaje*iva)

print("Division")
print(pasaje,"/",iva ,"=",pasaje/iva)

print("Potencia")
print(pasaje,"**",iva ,"=",pasaje**iva)

print("Division entera")
print(pasaje,"//",iva ,"=",pasaje//iva)

print("Modulo")
print(pasaje,"%",iva ,"=",pasaje%iva)

print("Operadores de Asignacion")
print("==========================")

